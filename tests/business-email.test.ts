import { test, after } from 'node:test';
import assert from 'node:assert/strict';
import { buildApi } from '../services/api/src/app.js';
import { id, pool } from '../packages/database/src/index.js';
const origin='http://127.0.0.1:4310';
const codes=new Map<string,string>();
const app=await buildApi({serveWeb:false,rateLimitMax:10000,personal:{codeSecret:'business-test-only-secret',sendCode:async(email,code)=>{codes.set(email,code);}}});
after(async()=>{await app.close();await pool.end();});

test('Business email account is distinct from Personal and gated by sandbox KYB',async()=>{
  const email=`${id('biz')}@example.test`;
  await pool.query('INSERT INTO personal_users(id,email) VALUES($1,$2) ON CONFLICT(email) DO NOTHING',[id('usr'),email]);
  const personalStart=await app.inject({method:'POST',url:'/personal/api/auth/start',headers:{origin},payload:{email}});
  assert.equal(personalStart.statusCode,200,personalStart.body);
  const personalCode=codes.get(email);
  const businessStart=await app.inject({method:'POST',url:'/business/api/auth/start',headers:{origin},payload:{email}});
  assert.equal(businessStart.statusCode,200,businessStart.body);
  const businessCode=codes.get(email);
  const wrongCode=personalCode===businessCode?'000000'===businessCode?'000001':'000000':personalCode;
  const cross=await app.inject({method:'POST',url:'/business/api/auth/verify',headers:{origin},payload:{challenge_id:businessStart.json().challenge_id,code:wrongCode}});
  assert.equal(cross.statusCode,401);
  const login=await app.inject({method:'POST',url:'/business/api/auth/verify',headers:{origin},payload:{challenge_id:businessStart.json().challenge_id,code:businessCode,name:'Test Business'}});
  assert.equal(login.statusCode,200,login.body);
  assert.equal(login.json().auth_method,'email');
  assert.match(String(login.headers['set-cookie']),/HttpOnly/);
  const cookie=String(login.headers['set-cookie']).split(';')[0];
  const session=await app.inject({url:'/console/session',headers:{cookie}});
  assert.equal(session.json().merchant_id,login.json().merchant_id);
  const account=await app.inject({url:'/business/api/account',headers:{cookie}});
  assert.equal(account.json().kyb_required,true);
  assert.equal(account.json().kyb_state,'not_started');
  const beforeBalance=await app.inject({url:'/v1/balances',headers:{cookie}});
  assert.equal(beforeBalance.json().data.find((b:{asset:string;purpose:string})=>b.asset==='NGN'&&b.purpose==='available')?.minor,'0');
  const headers={origin,cookie,'x-kora-csrf':login.json().csrf_token};
  const blocked=await app.inject({method:'POST',url:'/v1/quotes',headers:{...headers,'idempotency-key':id('key')},payload:{}});
  assert.equal(blocked.statusCode,403,blocked.body);
  assert.equal(blocked.json().error.code,'sandbox_kyb_required');
  const approve=await app.inject({method:'POST',url:'/business/api/sandbox/verify',headers,payload:{acknowledge_simulation:true}});
  assert.equal(approve.statusCode,200,approve.body);
  assert.equal((await app.inject({method:'POST',url:'/business/api/sandbox/verify',headers,payload:{acknowledge_simulation:true}})).statusCode,200);
  const afterBalance=await app.inject({url:'/v1/balances',headers:{cookie}});
  assert.equal(afterBalance.json().data.find((b:{asset:string;purpose:string})=>b.asset==='NGN'&&b.purpose==='available')?.minor,'250000000');
  const afterApproval=await app.inject({method:'POST',url:'/v1/quotes',headers:{...headers,'idempotency-key':id('key')},payload:{}});
  assert.notEqual(afterApproval.json().error?.code,'sandbox_kyb_required');
  const replay=await app.inject({method:'POST',url:'/business/api/auth/verify',headers:{origin},payload:{challenge_id:businessStart.json().challenge_id,code:businessCode}});
  assert.equal(replay.statusCode,401);
});
